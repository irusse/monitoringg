def cols(rows):
    out = []
    for c in range(5):
        b = 0
        for r, row in enumerate(rows):
            if c < len(row) and row[c] == "#":
                b |= 1 << r
        out.append(b)
    return out


def main():
    order = list("АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ")
    lines = [
        "#pragma once",
        "// 6x8 OLED Cyrillic (5x7 glyphs, xAdvance 6). Generated; do not edit.",
        "#include <stdint.h>",
        "",
        "static const uint8_t kOledCyrUpper[][5] = {",
    ]
    for ch in order:
        c = cols(ART[ch])
        hexes = ", ".join("0x%02X" % x for x in c)
        lines.append("    {%s}, // %s" % (hexes, ch))
    lines.append("};")
    lines.append("")
    dest = Path(__file__).resolve().parent.parent / "include" / "display" / "font6x8_cyr.h"
    dest.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", dest)


if __name__ == "__main__":
    main()
